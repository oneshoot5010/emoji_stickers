    'noha', 'mona', 'sara', 'sarah', 'mariam', 'maryam', 'nada', 'hana',
    'hala', 'dina', 'rania', 'shaimaa', 'aya', 'esraa', 'hagar', 'hajar',
    'fatma', 'fatima', 'salma', 'laila', 'layla', 'yasmin', 'nermin', 'heba',
    'rana', 'reem', 'jana', 'lina', 'mai', 'menna', 'rahma', 'doaa',
    'amira', 'farah', 'habiba', 'malak', 'nancy', 'passant', 'rawan', 'sandy',
  };

  static bool isFemale(String name) {
    final n = _norm(name);
    if (n.isEmpty) return false;
    if (n.startsWith('عبد')) return false;
    if (_maleEndingH.contains(n)) return false;
    if (_female.contains(n)) return true;
    if (n.endsWith('ه') && n.length > 2) return true;
    return false;
  }
}
