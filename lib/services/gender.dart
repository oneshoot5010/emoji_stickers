/// بيخمّن الاسم مذكر ولا مؤنث (للصيغة في ستيكرات باسمك).
/// لو التخمين غلط، المستخدم يختار بإيده من الإعدادات.
class NameGender {
  NameGender._();

  static String _norm(String s) {
    var t = s.trim().split(RegExp(r'\s+')).first.toLowerCase();
    t = t
        .replaceAll(RegExp('[\u064B-\u065F\u0670\u0640]'), '')
        .replaceAll(RegExp('[أإآٱ]'), 'ا')
        .replaceAll('ة', 'ه')
        .replaceAll('ى', 'ي');
    return t;
  }

  // أسماء ختمها ه/ة بس مذكرة
